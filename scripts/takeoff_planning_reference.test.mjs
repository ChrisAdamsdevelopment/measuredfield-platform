import assert from "node:assert/strict";
import {planningOptions,planningSelection,planningPriceProtected,PLANNING_SOURCE} from "../app/static/takeoff/src/planning-reference.mjs";
import {computeAssembly} from "../app/static/takeoff/src/assemblies.mjs";
import {buildEstimate} from "../app/static/takeoff/src/estimate.mjs";
const line=(key,q=105.6)=>({line_id:"test",material_key:key,assembly_id:"wall_drywall",description:"Synthetic test board",layer:"new",unit:"sf",qty:q/1.1,qty_with_waste:q,waste_pct:10,formula:"synthetic",measurement_ids:["m"],price_class:"retail",needs:[]});
const a=line("gypsum_board_standard");
const opts=planningOptions(a);
assert.equal(opts.length,1);assert.equal(opts[0].packages,4);assert.equal(opts[0].amount_cents,5600);
assert.equal(planningOptions(line("gypsum_board_type_x"))[0].reference_id,"fire-resistant-drywall");
assert.equal(planningOptions(line("gypsum_board_type_x"))[0].amount_cents,6800);
assert.equal(planningOptions({...a,unit:"lf"}).length,0);
assert.equal(planningOptions({...a,needs:["engineer_spec"]}).length,0);
assert.equal(planningOptions({...a,needs:["field_verify","owner_selection"]}).length,1);
assert.equal(planningOptions({...a,measurement_ids:[]}).length,0);
assert.equal(planningOptions({...a,material_key:"unknown"}).length,0);
assert.throws(()=>planningSelection(a,opts[0].reference_id,false));
assert.throws(()=>planningSelection(a,"fire-resistant-drywall",true));
const selection=planningSelection(a,opts[0].reference_id,true);
assert.equal(selection.mode,"allowance");assert.equal(selection.planning_reference.license,"CC BY 4.0");
const est=buildEstimate({lines:[a],selections:[selection],settings:{tax_rate_pct:0,shipping_cents:0},asOf:"2026-11-25"});
assert.equal(est.totals.allowance_cents,5600);
const revised=buildEstimate({lines:[line("gypsum_board_standard",211.2)],selections:[selection],settings:{tax_rate_pct:0,shipping_cents:0},asOf:"2026-11-25"});
assert.equal(revised.lines[0].extended_cents,null);
const actual=computeAssembly("tile_floor",{area_sf:15},{},{measurement_ids:["test"],layer:"new"});
assert(actual.some(l=>planningOptions(l).length>0));
assert.equal(PLANNING_SOURCE.license,"CC BY 4.0");
console.log("PLANNING_REFERENCE_TEST_PASS",JSON.stringify({standard_cents:5600,type_x_cents:6800,stale_rejected:true,actual_assembly:true}));

assert.equal(planningOptions({...a,flags:["calibration_unverified"]}).length,0);
assert.deepEqual(planningOptions(line("gypsum_board")).map(x=>x.reference_id),["standard-drywall"]);
assert.equal(planningPriceProtected(a,null,[{id:"q",line_ids:[a.line_id]}]),true);
assert.equal(planningPriceProtected(a,{mode:"unpriced"},[],{quote_id:"q"}),true);
assert.equal(planningPriceProtected(a,{mode:"contractor_rate"},[]),true);
assert.equal(planningPriceProtected(a,null,[{line_ids:["other"]}]),false);
console.log("PLANNING_REFERENCE_PROTECTION_PASS");
