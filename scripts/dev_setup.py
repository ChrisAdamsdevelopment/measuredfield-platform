"""Create a local development database and (optionally) a fictional demo business.

    python scripts/dev_setup.py --admin-url postgresql://postgres:PASSWORD@127.0.0.1:55432/postgres [--reset] [--demo]

What it does, on a LOOPBACK PostgreSQL server only:

1. creates the database ``mf_dev`` with two roles, mirroring production:
   ``mf_dev_owner`` (owns the schema, runs migrations) and ``mf_dev_app`` (the restricted
   role the application uses; no superuser, no BYPASSRLS, owns nothing);
2. runs the Alembic migrations and the runtime grants;
3. writes ``.env`` (git-ignored) with freshly generated local passwords and settings;
4. creates a platform operator, and with ``--demo`` walks a fictional business through
   the real HTTP flow: assessment -> approval -> workspace -> published site -> inquiry.

Nothing here sends email, takes payment or touches any non-local system. Generated
passwords are written to ``.env`` only; they are never printed.
"""
from __future__ import annotations

import argparse
import os
import re
import secrets
import sys
from pathlib import Path
from urllib.parse import urlsplit

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
DB, OWNER, APP = "mf_dev", "mf_dev_owner", "mf_dev_app"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--admin-url", default=os.environ.get("MF_TEST_PG_ADMIN_URL", ""))
    parser.add_argument("--reset", action="store_true", help="drop and recreate the mf_dev database")
    parser.add_argument("--demo", action="store_true", help="seed a fictional demo business")
    parser.add_argument("--port", default="8000")
    args = parser.parse_args()
    parts = urlsplit(args.admin_url)
    if parts.hostname not in ("localhost", "127.0.0.1", "::1"):
        print("Refusing: --admin-url must be a local PostgreSQL superuser URL.", file=sys.stderr)
        return 2
    from sqlalchemy import create_engine, text

    admin_url = re.sub(r"^postgres(ql)?(\+psycopg)?://", "postgresql+psycopg://", args.admin_url)
    admin = create_engine(admin_url, isolation_level="AUTOCOMMIT")
    hostport = f"{parts.hostname}:{parts.port or 5432}"
    owner_pw, app_pw = secrets.token_hex(16), secrets.token_hex(16)
    with admin.connect() as conn:
        exists = conn.execute(text("SELECT 1 FROM pg_database WHERE datname = :d"), {"d": DB}).scalar()
        if exists and not args.reset:
            print(f"Database {DB} already exists. Re-run with --reset to rebuild it (this erases local demo data).")
            return 1
        conn.execute(text(f"DROP DATABASE IF EXISTS {DB} WITH (FORCE)"))
        for role, password in ((OWNER, owner_pw), (APP, app_pw)):
            if not conn.execute(text("SELECT 1 FROM pg_roles WHERE rolname = :r"), {"r": role}).scalar():
                conn.execute(text(f"CREATE ROLE {role} LOGIN NOSUPERUSER NOBYPASSRLS"))
            conn.execute(text(f"ALTER ROLE {role} LOGIN NOSUPERUSER NOBYPASSRLS PASSWORD '{password}'"))
        conn.execute(text(f"CREATE DATABASE {DB} OWNER {OWNER}"))
    admin.dispose()
    owner_url = f"postgresql+psycopg://{OWNER}:{owner_pw}@{hostport}/{DB}"
    app_url = f"postgresql+psycopg://{APP}:{app_pw}@{hostport}/{DB}"

    operator_pw, owner_login_pw = secrets.token_urlsafe(18), secrets.token_urlsafe(18)
    env = {
        "MF_ENV": "development", "DATABASE_URL": app_url, "MIGRATION_DATABASE_URL": owner_url,
        "MF_SECRET_KEY": secrets.token_hex(32), "MF_APP_HOSTS": "localhost,127.0.0.1,testserver",
        "MF_SITES_BASE_DOMAIN": "sites.localhost", "MF_PUBLIC_BASE_URL": f"http://localhost:{args.port}",
        "MF_INLINE_JOBS": "true", "MF_EMAIL_PROVIDER": "none", "MF_PAYMENT_PROVIDER": "none",
        "MF_AI_PROVIDER": "none",
        "MF_DEV_OPERATOR_EMAIL": "operator@measuredfield.test", "MF_DEV_OPERATOR_PASSWORD": operator_pw,
        "MF_DEV_OWNER_EMAIL": "owner@canyonview.example", "MF_DEV_OWNER_PASSWORD": owner_login_pw,
    }
    (ROOT / ".env").write_text(
        "# Local development only. Generated by scripts/dev_setup.py. Never commit this file.\n"
        + "".join(f"{k}={v}\n" for k, v in env.items()), encoding="utf-8")
    os.chdir(ROOT)
    os.environ.update(env)

    # Migrate as the owner, in this process only.
    os.environ["DATABASE_URL"] = owner_url
    from app.config import get_settings
    from app.db import isolation_self_check, reset_engine
    get_settings.cache_clear()
    from alembic import command
    from alembic.config import Config
    command.upgrade(Config(str(ROOT / "alembic.ini")), "head")
    owner_engine = create_engine(owner_url, isolation_level="AUTOCOMMIT")
    grants = re.sub(r"--.*", "", (ROOT / "scripts" / "grant_runtime_role.sql").read_text(encoding="utf-8"))
    with owner_engine.connect() as conn:
        for statement in (s.strip() for s in grants.split(";")):
            if statement and not statement.upper().startswith("ALTER ROLE"):
                conn.execute(text(statement.replace("mf_app", APP)))
    owner_engine.dispose()

    os.environ["DATABASE_URL"] = app_url
    get_settings.cache_clear()
    reset_engine()
    problems = isolation_self_check()
    if problems:
        print("Isolation self-check FAILED:", *problems, sep="\n  ", file=sys.stderr)
        return 3
    print("Database ready. Tenant-isolation self-check passed as the restricted role.")

    os.environ["MF_OPERATOR_PASSWORD"] = operator_pw
    from app.cli import create_operator
    create_operator(env["MF_DEV_OPERATOR_EMAIL"])
    if args.demo:
        seed_demo(env)
    print(f"""
Start the app:   python -m uvicorn app.main:app --port {args.port}
Marketing site:  http://localhost:{args.port}/
Workspace:       http://localhost:{args.port}/login     (MF_DEV_OWNER_EMAIL / MF_DEV_OWNER_PASSWORD in .env)
Operator:        http://localhost:{args.port}/operator  (MF_DEV_OPERATOR_EMAIL / MF_DEV_OPERATOR_PASSWORD in .env)
Customer site:   http://canyon-view.sites.localhost:{args.port}/   (after --demo)
Sign-in details are in {ROOT / '.env'} and were not printed.""")
    return 0


def seed_demo(env: dict) -> None:
    """Drive the real HTTP routes with a fictional business. Everything is synthetic."""
    from sqlalchemy import select
    from starlette.testclient import TestClient

    from app.db import session_scope
    from app.main import create_app
    from app.models import EmailMessage, ServiceOrder

    app = create_app()

    def client(host="testserver"):
        return TestClient(app, base_url=f"http://{host}", follow_redirects=False)

    def csrf(c, page="/app/settings"):
        return re.search(r'name="csrf" value="([0-9a-f]{64})"', c.get(page).text).group(1)

    visitor = client()
    r = visitor.post("/assessment", data={
        "excited": "We just added a move-out cleaning service and property managers keep recommending us.",
        "blocker": "I lose track of who I need to call back, quotes take me all evening, and our website is just a Facebook page.",
        "business_name": "Canyon View Cleaning (fictional)", "contact_name": "Dana Demo",
        "email": env["MF_DEV_OWNER_EMAIL"], "industry": "cleaning", "consent": "yes", "website": ""})
    token = r.headers["location"].rsplit("/", 1)[1]
    r = visitor.post(f"/assessment/r/{token}/order", data={"offer_code": "consult", "approved_name": "Dana Demo", "agree": "yes"})
    order_id = r.headers["location"].split("/order/")[1].split("?")[0]

    op = client()
    op.post("/login", data={"email": env["MF_DEV_OPERATOR_EMAIL"], "password": env["MF_DEV_OPERATOR_PASSWORD"]})
    op.post(f"/operator/orders/{order_id}/provision",
            data={"csrf": csrf(op, "/operator"), "reason": "Fictional demo business (no payment)"})
    with session_scope() as db:
        org_id = db.scalar(select(ServiceOrder.org_id).where(ServiceOrder.id == order_id))
        body = db.scalar(select(EmailMessage.body).where(EmailMessage.to_email == env["MF_DEV_OWNER_EMAIL"],
                                                         EmailMessage.kind == "invite"))
    invite = re.search(r"token=([A-Za-z0-9_\-]+)", body).group(1)
    owner = client()
    owner.post("/accept-invite", data={"token": invite, "name": "Dana Demo", "password": env["MF_DEV_OWNER_PASSWORD"]})
    token_csrf = csrf(owner)
    owner.post("/app/website/save", data={
        "csrf": token_csrf, "name": "Canyon View Cleaning", "city": "Fictionville, AZ", "industry": "cleaning",
        "color": "ocean", "email": "hello@canyonview.example", "phone": "(555) 010-0142",
        "about": "A fictional, locally owned cleaning company used to demonstrate MeasuredField.",
        "headline": "", "intro": "", "response_window": "one_business_day", "structured_intake": "on",
        "services": "Regular cleaning | Weekly or every other week\nDeep cleaning | Top to bottom, inside appliances\n"
                    "Move-out cleaning | Ready for the next tenant", "slug": "canyon-view"})
    owner.post("/app/website/version", data={"csrf": token_csrf, "note": "First version"})
    version = re.search(r"/app/website/versions/([0-9a-f-]{36})/approve", owner.get("/app/website").text).group(1)
    owner.post(f"/app/website/versions/{version}/approve", data={"csrf": token_csrf})
    owner.post(f"/app/website/versions/{version}/publish", data={"csrf": token_csrf})
    site = client("canyon-view.sites.localhost")
    for kind in ("page_view",) * 7 + ("form_start",) * 2:
        site.post("/api/event", json={"kind": kind})
    for name, service, message in (
        ("Riley Resident (fictional)", "Deep cleaning", "Could you quote a deep clean for a three bedroom house next week?"),
        ("Morgan Manager (fictional)", "Move-out cleaning", "We manage 12 units and need a regular move-out cleaner."),
    ):
        site.post("/api/lead", json={"name": name, "email": name.split()[0].lower() + "@visitor.example",
                                     "service": service, "timing": "this_month", "message": message})
        with session_scope() as db:
            db.execute(__import__("sqlalchemy").text("DELETE FROM rate_limits"))
    print(f"Demo business seeded (organization {org_id}): 1 published site, 2 fictional inquiries.")


if __name__ == "__main__":
    raise SystemExit(main())
