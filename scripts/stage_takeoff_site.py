"""Copy only reviewed takeoff browser assets into the existing MeasuredField app.

Usage: python scripts/stage_takeoff_site.py PATH_TO_ISOLATED_PILOT_BUNDLE
This is a developer release step; app/static/takeoff contains the deployed files.
No customer PDF, credential, environment file, backend endpoint or test fixture
may be copied. The reference bundle is generated by independent preview builder.
"""
from __future__ import annotations
import hashlib
import json
import shutil
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
TARGET = ROOT / "app" / "static" / "takeoff"
SENTINEL = ".managed-takeoff-assets"
ALLOWED_EXT = {".mjs", ".js", ".css", ".html", ".svg", ".csv", ".wasm",
               ".bcmap", ".pfb", ".properties", ".ttf", ".otf", ".txt"}
MAX_TOTAL = 80 * 1024 * 1024
MAX_PER_FILE = 10 * 1024 * 1024


def stage(from_bundle: Path) -> dict:
    if not (from_bundle / "manifest.json").is_file():
        raise ValueError("Reviewed preview manifest required")
    expected = json.loads((from_bundle / "manifest.json").read_text(encoding="utf-8"))
    files = expected.get("source_sha256", {})
    if expected.get("format") != "mf.preview.static-assets/1" or not isinstance(files, dict):
        raise ValueError("Invalid preview release manifest")
    if not 35 <= len(files) <= 85:
        raise ValueError("Unexpected asset count")
    data = {}
    total = 0
    for rel, sha in files.items():
        if rel == "server.py":
            # Separate pilot server deliberately excluded from canonical platform.
            continue
        path = Path(rel)
        if (not rel.startswith(("site/public/", "site/src/"))
            or path.is_absolute() or ".." in path.parts or "\\" in rel
            or not (path.suffix.lower() in ALLOWED_EXT or
                    (path.name in {"LICENSE", "SHA256SUMS"} and
                     "vendor" in path.parts))
            or any(part.startswith(".") for part in path.parts)):
            raise ValueError("Unsafe asset path")
        disk = from_bundle.resolve() / path
        if not disk.is_file() or disk.is_symlink():
            raise ValueError("Missing or symlink asset")
        payload = disk.read_bytes()
        if len(payload) > MAX_PER_FILE or hashlib.sha256(payload).hexdigest() != sha:
            raise ValueError("Asset fingerprint mismatch")
        if any(secret in payload for secret in (b"nvapi-", b"sk-proj-", b"ghp_",
                      b"PRIVATE_AUTH", b"06_PLAN_INBOX_PRIVATE", b"CASE_2026_001_BATH")):
            raise ValueError("Private data detected")
        total += len(payload)
        data[str(Path(*path.parts[1:])).replace("\\", "/")] = payload
    if total > MAX_TOTAL:
        raise ValueError("Preview assets exceed expected size")
    if not any(k.endswith("public/guided/index.html") for k in data):
        raise ValueError("Guided page missing")
    if TARGET.exists():
        if not (TARGET / SENTINEL).is_file():
            raise ValueError("Refusing to overwrite an unmanaged static directory")
        shutil.rmtree(TARGET)
    TARGET.mkdir(parents=True)
    (TARGET / SENTINEL).write_text("Allowlisted takeoff pilot assets, no customer files.\n")
    for name, payload in data.items():
        output = TARGET / name
        output.parent.mkdir(parents=True, exist_ok=True)
        output.write_bytes(payload)
    print("TAKEOFF_ASSETS_STAGED", len(data), "files", total, "bytes")
    return {"files":len(data),"bytes":total}


if __name__ == "__main__":
    if len(sys.argv) != 2:
        raise SystemExit("Pass reviewed release bundle directory")
    stage(Path(sys.argv[1]))
